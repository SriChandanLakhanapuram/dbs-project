-- Touchline football league schema (Oracle 12c+). Run once while connected as the
-- application owner (for example DBMS) in SQL Developer. The app does not run DDL.

CREATE TABLE countries (
    country_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL UNIQUE
);

CREATE TABLE leagues (
    league_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(120) NOT NULL,
    country_id NUMBER REFERENCES countries(country_id),
    CONSTRAINT uq_league_country UNIQUE (name, country_id)
);

CREATE TABLE seasons (
    season_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    league_id NUMBER NOT NULL REFERENCES leagues(league_id),
    label VARCHAR2(20) NOT NULL,
    start_date DATE,
    end_date DATE,
    CONSTRAINT uq_season_league UNIQUE (league_id, label),
    CONSTRAINT ck_season_dates CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);

CREATE TABLE stadiums (
    stadium_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(120) NOT NULL,
    location VARCHAR2(160),
    capacity NUMBER(9),
    CONSTRAINT ck_stadium_capacity CHECK (capacity IS NULL OR capacity >= 0)
);

CREATE TABLE teams (
    team_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    league_id NUMBER REFERENCES leagues(league_id),
    stadium_id NUMBER REFERENCES stadiums(stadium_id),
    name VARCHAR2(120) NOT NULL UNIQUE,
    founded_year NUMBER(4),
    CONSTRAINT ck_team_founded CHECK (founded_year IS NULL OR founded_year BETWEEN 1800 AND 2100)
);

CREATE TABLE coaches (
    coach_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id NUMBER REFERENCES teams(team_id),
    name VARCHAR2(120) NOT NULL,
    nationality VARCHAR2(80)
);

CREATE TABLE players (
    player_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id NUMBER REFERENCES teams(team_id),
    name VARCHAR2(120) NOT NULL,
    date_of_birth DATE,
    nationality VARCHAR2(80),
    position VARCHAR2(40),
    height_cm NUMBER(5,2),
    jersey_no NUMBER(3),
    preferred_foot VARCHAR2(10),
    CONSTRAINT ck_player_foot CHECK (preferred_foot IS NULL OR preferred_foot IN ('Left','Right','Both'))
);

CREATE TABLE matches (
    match_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id NUMBER NOT NULL REFERENCES seasons(season_id),
    stadium_id NUMBER REFERENCES stadiums(stadium_id),
    home_team_id NUMBER NOT NULL REFERENCES teams(team_id),
    away_team_id NUMBER NOT NULL REFERENCES teams(team_id),
    match_date TIMESTAMP NOT NULL,
    status VARCHAR2(20) DEFAULT 'Scheduled' NOT NULL,
    home_goals NUMBER(2) DEFAULT 0 NOT NULL,
    away_goals NUMBER(2) DEFAULT 0 NOT NULL,
    CONSTRAINT ck_match_teams CHECK (home_team_id <> away_team_id),
    CONSTRAINT ck_match_status CHECK (status IN ('Scheduled','Live','Completed','Postponed','Cancelled')),
    CONSTRAINT ck_match_goals CHECK (home_goals >= 0 AND away_goals >= 0)
);

CREATE TABLE standings (
    standing_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id NUMBER NOT NULL REFERENCES seasons(season_id),
    team_id NUMBER NOT NULL REFERENCES teams(team_id),
    played NUMBER(3) DEFAULT 0 NOT NULL,
    won NUMBER(3) DEFAULT 0 NOT NULL,
    drawn NUMBER(3) DEFAULT 0 NOT NULL,
    lost NUMBER(3) DEFAULT 0 NOT NULL,
    goals_for NUMBER(4) DEFAULT 0 NOT NULL,
    goals_against NUMBER(4) DEFAULT 0 NOT NULL,
    points NUMBER(4) DEFAULT 0 NOT NULL,
    CONSTRAINT uq_standing_team_season UNIQUE (season_id, team_id)
);

CREATE TABLE referees (
    referee_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(120) NOT NULL,
    nationality VARCHAR2(80)
);

CREATE TABLE match_refs (
    match_id NUMBER NOT NULL REFERENCES matches(match_id) ON DELETE CASCADE,
    referee_id NUMBER NOT NULL REFERENCES referees(referee_id),
    CONSTRAINT pk_match_refs PRIMARY KEY (match_id, referee_id)
);

CREATE TABLE lineups (
    lineup_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id NUMBER NOT NULL REFERENCES matches(match_id) ON DELETE CASCADE,
    team_id NUMBER NOT NULL REFERENCES teams(team_id),
    player_id NUMBER NOT NULL REFERENCES players(player_id),
    position VARCHAR2(40),
    is_starting CHAR(1) DEFAULT 'Y' NOT NULL,
    CONSTRAINT ck_lineup_starting CHECK (is_starting IN ('Y','N')),
    CONSTRAINT uq_lineup_player UNIQUE (match_id, player_id)
);

CREATE TABLE scorers (
    scorer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id NUMBER NOT NULL REFERENCES matches(match_id) ON DELETE CASCADE,
    player_id NUMBER NOT NULL REFERENCES players(player_id),
    team_id NUMBER NOT NULL REFERENCES teams(team_id),
    minute NUMBER(3) NOT NULL,
    CONSTRAINT ck_scorer_minute CHECK (minute BETWEEN 1 AND 130)
);

CREATE TABLE cards (
    card_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id NUMBER NOT NULL REFERENCES matches(match_id) ON DELETE CASCADE,
    player_id NUMBER NOT NULL REFERENCES players(player_id),
    card_type VARCHAR2(10) NOT NULL,
    minute NUMBER(3) NOT NULL,
    CONSTRAINT ck_card_type CHECK (card_type IN ('Yellow','Red')),
    CONSTRAINT ck_card_minute CHECK (minute BETWEEN 1 AND 130)
);

CREATE TABLE substitutions (
    substitution_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id NUMBER NOT NULL REFERENCES matches(match_id) ON DELETE CASCADE,
    player_out_id NUMBER NOT NULL REFERENCES players(player_id),
    player_in_id NUMBER NOT NULL REFERENCES players(player_id),
    minute NUMBER(3) NOT NULL,
    CONSTRAINT ck_sub_different_players CHECK (player_out_id <> player_in_id),
    CONSTRAINT ck_sub_minute CHECK (minute BETWEEN 1 AND 130)
);

CREATE TABLE transfers (
    transfer_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_id NUMBER REFERENCES seasons(season_id),
    player_id NUMBER NOT NULL REFERENCES players(player_id),
    from_team_id NUMBER REFERENCES teams(team_id),
    to_team_id NUMBER NOT NULL REFERENCES teams(team_id),
    transfer_date DATE NOT NULL,
    fee NUMBER(14,2) DEFAULT 0 NOT NULL,
    CONSTRAINT ck_transfer_teams CHECK (from_team_id IS NULL OR from_team_id <> to_team_id),
    CONSTRAINT ck_transfer_fee CHECK (fee >= 0)
);

CREATE INDEX ix_matches_season_date ON matches(season_id, match_date);
CREATE INDEX ix_players_team ON players(team_id);
CREATE INDEX ix_standings_season_points ON standings(season_id, points DESC);

COMMIT;
